create table video.ingestion_jobs (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null,
    video_id uuid not null,
    target_version_id uuid not null,
    idempotency_key uuid not null,
    status text not null check (status in (
        'awaiting_upload', 'queued', 'running', 'retry_scheduled',
        'ready', 'failed', 'cancelled'
    )),
    stage text check (stage is null or stage in (
        'acquire_source', 'media_metadata', 'transcript', 'resources',
        'frame_selection', 'ocr', 'visual_analysis', 'spatial_regions',
        'indexing', 'quality_gates', 'publish'
    )),
    progress_completed integer not null default 0 check (
        progress_completed >= 0
    ),
    progress_total integer check (
        progress_total is null or progress_total >= 0
    ),
    progress_unit text,
    attempt_count integer not null default 0 check (attempt_count >= 0),
    max_attempts integer not null default 3 check (max_attempts > 0),
    next_attempt_at timestamptz,
    lease_owner text,
    lease_expires_at timestamptz,
    heartbeat_at timestamptz,
    cancellation_requested_at timestamptz,
    last_error_code text,
    last_error_message text,
    last_error_retryable boolean,
    staging_storage_backend text check (
        staging_storage_backend is null
        or staging_storage_backend in ('filesystem', 'supabase', 's3')
    ),
    staging_storage_key text,
    cost_cap_usd numeric(10, 6) not null default 0.50 check (
        cost_cap_usd > 0
    ),
    actual_cost_usd numeric(10, 6) not null default 0 check (
        actual_cost_usd >= 0 and actual_cost_usd <= cost_cap_usd
    ),
    provenance_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(provenance_json) = 'object'
    ),
    created_at timestamptz not null default now(),
    started_at timestamptz,
    updated_at timestamptz not null default now(),
    completed_at timestamptz,
    unique (id, owner_id),
    unique (id, video_id, owner_id),
    unique (owner_id, idempotency_key),
    foreign key (video_id, owner_id)
        references video.videos(id, owner_id) on delete cascade,
    foreign key (target_version_id, video_id, owner_id)
        references video.ingestion_versions(id, video_id, owner_id)
        on delete cascade,
    check (
        (staging_storage_backend is null and staging_storage_key is null)
        or
        (staging_storage_backend is not null
            and staging_storage_key is not null
            and btrim(staging_storage_key) <> ''
            and staging_storage_key like owner_id::text || '/%')
    ),
    check (
        (status in ('ready', 'failed', 'cancelled'))
        = (completed_at is not null)
    ),
    check (
        progress_total is null or progress_completed <= progress_total
    ),
    check (started_at is null or started_at >= created_at),
    check (completed_at is null or completed_at >= created_at)
);


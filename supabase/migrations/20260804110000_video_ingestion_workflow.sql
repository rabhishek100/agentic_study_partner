do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'transcript_sources', 'transcript_segments', 'resource_pages',
        'ingestion_versions', 'ingestion_jobs', 'ingestion_job_events',
        'ingestion_stage_checkpoints', 'resource_suggestions'
    ] loop
        execute format('alter table video.%I enable row level security', table_name);
        execute format(
            'create policy %I on video.%I for select to authenticated '
            'using (owner_id = (select auth.uid()))',
            table_name || '_owner_read',
            table_name
        );
        execute format(
            'grant select on video.%I to authenticated',
            table_name
        );
    end loop;
end $$;


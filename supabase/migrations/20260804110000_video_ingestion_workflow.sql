    owner_id uuid not null,
    video_id uuid not null,
    video_source_id uuid not null,
    version_number integer not null check (version_number > 0),
    status text not null default 'building' check (
        status in ('building', 'ready', 'degraded', 'failed', 'cancelled')
    ),
    config_json jsonb not null check (jsonb_typeof(config_json) = 'object'),
    config_hash text not null check (config_hash ~ '^[0-9a-f]{64}$'),
    dependency_hashes_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(dependency_hashes_json) = 'object'
    ),
    model_prompt_versions_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(model_prompt_versions_json) = 'object'
    ),
    resource_set_hash text check (
        resource_set_hash is null or resource_set_hash ~ '^[0-9a-f]{64}$'
    ),
    quality_gates_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(quality_gates_json) = 'object'
    ),
    cost_cap_usd numeric(10, 6) not null default 0.50 check (
        cost_cap_usd > 0
    ),
    actual_cost_usd numeric(10, 6) not null default 0 check (
        actual_cost_usd >= 0 and actual_cost_usd <= cost_cap_usd
    ),
    started_at timestamptz not null default now(),
    completed_at timestamptz,
    published_at timestamptz,
    error_code text,
    error_message text,
    unique (id, video_id, owner_id),
    unique (video_id, version_number),
    foreign key (video_id, owner_id)
        references video.videos(id, owner_id) on delete cascade,
    foreign key (video_source_id, video_id, owner_id)
        references video.video_sources(id, video_id, owner_id) on delete cascade,
    check (
        (status in ('ready', 'degraded', 'failed', 'cancelled'))
        = (completed_at is not null)
    ),
    check (
        (status in ('ready', 'degraded')) = (published_at is not null)
    ),
    check (
        status not in ('ready', 'degraded')
        or quality_gates_json <> '{}'::jsonb
    ),
    check (published_at is null or published_at >= started_at),
    check (completed_at is null or completed_at >= started_at),
    check (published_at is null or published_at <= completed_at)
);


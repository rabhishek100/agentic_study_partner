    add constraint videos_ready_requires_current_version
        check (
            (readiness_status in ('ready', 'degraded'))
            = (current_ingestion_version_id is not null)
        );

create or replace function video.validate_current_ingestion_version()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
    version_status text;
begin
    if new.current_ingestion_version_id is null then
        return new;
    end if;

    select current.status
    into version_status
    from video.ingestion_versions as current
    where current.id = new.current_ingestion_version_id
      and current.video_id = new.id
      and current.owner_id = new.owner_id;

    if version_status is null or version_status <> new.readiness_status then
        raise check_violation using message =
            'current ingestion version must be published with the same readiness status';
    end if;
    return new;
end;
$$;

create trigger videos_validate_current_ingestion_version
    before insert or update of current_ingestion_version_id, readiness_status
    on video.videos
    for each row execute function video.validate_current_ingestion_version();


create table video.resource_suggestions (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null,
    video_id uuid not null,
    job_id uuid,
    suggested_kind text not null check (
        suggested_kind in ('pdf', 'external_link')
    ),
    url text not null check (btrim(url) <> ''),
    normalized_url text not null check (btrim(normalized_url) <> ''),
    title text,
    reason text,
    status text not null default 'pending' check (
        status in ('pending', 'confirmed', 'dismissed')
    ),
    confirmed_resource_id uuid,
    created_at timestamptz not null default now(),
    resolved_at timestamptz,
    unique (id, video_id, owner_id),
    unique (video_id, normalized_url),
    foreign key (video_id, owner_id)
        references video.videos(id, owner_id) on delete cascade,
    foreign key (job_id, video_id, owner_id)
        references video.ingestion_jobs(id, video_id, owner_id)
        on delete cascade,
    foreign key (confirmed_resource_id, owner_id)
        references video.resources(id, owner_id),
    check (
        (status = 'pending'
            and confirmed_resource_id is null
            and resolved_at is null)
        or
        (status = 'confirmed'
            and confirmed_resource_id is not null
            and resolved_at is not null)
        or
        (status = 'dismissed'
            and confirmed_resource_id is null
            and resolved_at is not null)
    )
);

create index idx_video_resource_suggestions_owner_video
    on video.resource_suggestions (owner_id, video_id, status, created_at);


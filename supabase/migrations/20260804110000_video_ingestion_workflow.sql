-- Durable transcript inputs and the resumable, versioned video-ingestion
-- workflow. Rows in this migration preserve enough provenance to rebuild all
-- visual and retrieval artifacts introduced by later migrations.

create table video.transcript_sources (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null,
    video_id uuid not null,
    video_source_id uuid not null,
    source_kind text not null check (
        source_kind in ('youtube_caption', 'openrouter_transcription')
    ),
    language text not null check (btrim(language) <> ''),
    provider text not null check (btrim(provider) <> ''),
    model_name text,
    model_revision text,
    storage_backend text not null check (
        storage_backend in ('filesystem', 'supabase', 's3')
    ),
    storage_key text not null check (
        btrim(storage_key) <> ''
        and storage_key like owner_id::text || '/%'
    ),
    content_hash text not null check (content_hash ~ '^[0-9a-f]{64}$'),
    timing_kind text not null check (timing_kind in ('cue', 'word')),
    coverage_ratio double precision check (
        coverage_ratio is null or coverage_ratio between 0 and 1
    ),
    detected_speech boolean,
    provenance_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(provenance_json) = 'object'
    ),
    cost_usd numeric(10, 6) not null default 0 check (cost_usd >= 0),
    created_at timestamptz not null default now(),
    unique (id, video_id, owner_id),
    unique (video_source_id, content_hash),
    foreign key (video_id, owner_id)
        references video.videos(id, owner_id) on delete cascade,
    foreign key (video_source_id, video_id, owner_id)
        references video.video_sources(id, video_id, owner_id) on delete cascade,
    check (
        source_kind <> 'openrouter_transcription'
        or (model_name is not null and btrim(model_name) <> '')
    )
);


create table video.evidence_units (
    id text not null check (id ~ '^[0-9a-f]{64}$'),
    owner_id uuid not null,
    video_id uuid not null,
    ingestion_version_id uuid not null,
    modality text not null check (modality in (
        'transcript', 'visual_frame', 'visual_event', 'resource_page'
    )),
    transcript_segment_id bigint,
    frame_id bigint,
    visual_event_id bigint,
    resource_page_id bigint,
    retrieval_text text not null check (btrim(retrieval_text) <> ''),
    start_ms bigint check (start_ms is null or start_ms >= 0),
    end_ms bigint check (
        end_ms is null or (start_ms is not null and end_ms >= start_ms)
    ),
    page_number integer check (page_number is null or page_number > 0),
    content_hash text not null check (content_hash ~ '^[0-9a-f]{64}$'),
    search_vector tsvector generated always as (
        to_tsvector('simple', coalesce(retrieval_text, ''))
    ) stored,
    created_at timestamptz not null default now(),
    primary key (id, owner_id),
    unique (id, ingestion_version_id, video_id, owner_id),
    unique (id, frame_id, ingestion_version_id, video_id, owner_id),
    foreign key (ingestion_version_id, video_id, owner_id)
        references video.ingestion_versions(id, video_id, owner_id)
        on delete cascade,
    foreign key (transcript_segment_id, video_id, owner_id)
        references video.transcript_segments(id, video_id, owner_id)
        on delete cascade,
    foreign key (frame_id, ingestion_version_id, video_id, owner_id)
        references video.frames(id, ingestion_version_id, video_id, owner_id)
        on delete cascade,
    foreign key (visual_event_id, ingestion_version_id, video_id, owner_id)
        references video.visual_events(id, ingestion_version_id, video_id, owner_id)
        on delete cascade,
    foreign key (resource_page_id, owner_id)
        references video.resource_pages(id, owner_id) on delete cascade,
    check (
        num_nonnulls(
            transcript_segment_id, frame_id, visual_event_id, resource_page_id
        ) = 1
    ),
    check (
        (modality = 'transcript'
            and transcript_segment_id is not null
            and start_ms is not null
            and end_ms is not null
            and page_number is null)
        or
        (modality = 'visual_frame'
            and frame_id is not null
            and start_ms is not null
            and end_ms is not null
            and page_number is null)
        or
        (modality = 'visual_event'
            and visual_event_id is not null
            and start_ms is not null
            and end_ms is not null
            and page_number is null)
        or
        (modality = 'resource_page'
            and resource_page_id is not null
            and start_ms is null
            and end_ms is null
            and page_number is not null)
    )
);

create index idx_video_evidence_units_owner_version_modality

-- Rebuildable, timestamp-addressable visual evidence. Image embeddings are
-- structurally limited to extracted diagram or drawing regions; other visual
-- types participate in retrieval through OCR and model-extracted text.

create table video.frames (
    id bigint generated by default as identity primary key,
    owner_id uuid not null,
    video_id uuid not null,
    ingestion_version_id uuid not null,
    frame_index integer not null check (frame_index >= 0),
    timestamp_ms bigint not null check (timestamp_ms >= 0),
    selection_reasons text[] not null check (
        coalesce(array_length(selection_reasons, 1), 0) > 0
    ),
    full_storage_backend text not null check (
        full_storage_backend in ('filesystem', 'supabase', 's3')
    ),
    full_storage_key text not null check (
        btrim(full_storage_key) <> ''
        and full_storage_key like owner_id::text || '/%'
    ),
    full_content_hash text not null check (
        full_content_hash ~ '^[0-9a-f]{64}$'
    ),
    preview_storage_backend text not null check (
        preview_storage_backend in ('filesystem', 'supabase', 's3')
    ),
    preview_storage_key text not null check (
        btrim(preview_storage_key) <> ''
        and preview_storage_key like owner_id::text || '/%'
    ),
    preview_content_hash text not null check (
        preview_content_hash ~ '^[0-9a-f]{64}$'
    ),
    perceptual_hash text not null check (
        perceptual_hash ~ '^[0-9a-f]{16,64}$'
    ),
    width integer not null check (width > 0),
    height integer not null check (height > 0),
    ocr_text text not null default '',
    ocr_confidence double precision check (
        ocr_confidence is null or ocr_confidence between 0 and 1
    ),
    ocr_engine text,
    ocr_version text,
    created_at timestamptz not null default now(),
    unique (id, ingestion_version_id, video_id, owner_id),
    unique (ingestion_version_id, frame_index),
    unique (ingestion_version_id, timestamp_ms),
    foreign key (ingestion_version_id, video_id, owner_id)
        references video.ingestion_versions(id, video_id, owner_id)
        on delete cascade
);

create index idx_video_frames_owner_video_timestamp
    on video.frames (owner_id, video_id, ingestion_version_id, timestamp_ms);
create index idx_video_frames_owner_full_hash
    on video.frames (owner_id, full_content_hash);

create table video.visual_observations (
    id bigint generated by default as identity primary key,
    owner_id uuid not null,
    video_id uuid not null,
    ingestion_version_id uuid not null,
    frame_id bigint not null,
    status text not null check (status in ('success', 'failed')),
    visual_types text[] not null default '{}'::text[] check (
        visual_types <@ array[
            'slide', 'code', 'equation', 'diagram', 'drawing', 'chart',
            'ui', 'terminal', 'person', 'other'
        ]::text[]
    ),
    summary text,
    visible_text text not null default '',
    technical_details_json jsonb not null default '{}'::jsonb check (
        jsonb_typeof(technical_details_json) = 'object'
    ),
    importance double precision check (
        importance is null or importance between 0 and 1
    ),
    confidence double precision check (
        confidence is null or confidence between 0 and 1
    ),
    model_name text not null check (btrim(model_name) <> ''),
    model_revision text not null check (btrim(model_revision) <> ''),
    prompt_version text not null check (btrim(prompt_version) <> ''),
    input_hash text not null check (input_hash ~ '^[0-9a-f]{64}$'),
    cost_usd numeric(10, 6) not null default 0 check (cost_usd >= 0),
    error_code text,
    error_message text,
    created_at timestamptz not null default now(),
    unique (id, frame_id, ingestion_version_id, video_id, owner_id),
    unique (frame_id),
    foreign key (frame_id, ingestion_version_id, video_id, owner_id)
        references video.frames(id, ingestion_version_id, video_id, owner_id)
        on delete cascade,
    check (
        (status = 'success'
            and summary is not null
            and btrim(summary) <> ''
            and coalesce(array_length(visual_types, 1), 0) > 0
            and error_code is null
            and error_message is null)
        or
        (status = 'failed'
            and summary is null
            and coalesce(array_length(visual_types, 1), 0) = 0
            and error_code is not null
            and btrim(error_code) <> '')
    )
);

create index idx_video_visual_observations_owner_version
    on video.visual_observations (
        owner_id, video_id, ingestion_version_id, status
    );


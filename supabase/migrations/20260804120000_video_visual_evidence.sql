create or replace function video.validate_evidence_locator()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
    source_start_ms bigint;
    source_end_ms bigint;
    source_page_number integer;
    source_resource_id uuid;
begin
    if new.modality = 'transcript' then
        select segment.start_ms, segment.end_ms
        into source_start_ms, source_end_ms
        from video.transcript_segments as segment
        where segment.id = new.transcript_segment_id
          and segment.video_id = new.video_id
          and segment.owner_id = new.owner_id;
    elsif new.modality = 'visual_frame' then
        select frame.timestamp_ms, frame.timestamp_ms
        into source_start_ms, source_end_ms
        from video.frames as frame
        where frame.id = new.frame_id
          and frame.ingestion_version_id = new.ingestion_version_id
          and frame.video_id = new.video_id
          and frame.owner_id = new.owner_id;
    elsif new.modality = 'visual_event' then
        select event.start_ms, event.end_ms
        into source_start_ms, source_end_ms
        from video.visual_events as event
        where event.id = new.visual_event_id
          and event.ingestion_version_id = new.ingestion_version_id
          and event.video_id = new.video_id
          and event.owner_id = new.owner_id;
    elsif new.modality = 'resource_page' then
        select page.page_number, page.resource_id
        into source_page_number, source_resource_id
        from video.resource_pages as page
        where page.id = new.resource_page_id
          and page.owner_id = new.owner_id;

        if source_page_number is null
           or source_page_number is distinct from new.page_number
           or not exists (
                select 1
                from video.video_resources as linked
                where linked.video_id = new.video_id
                  and linked.resource_id = source_resource_id
                  and linked.owner_id = new.owner_id
           ) then
            raise check_violation using message =
                'resource evidence must match a page linked to this video';
        end if;
        return new;
    end if;

    if source_start_ms is null
       or source_start_ms is distinct from new.start_ms
       or source_end_ms is distinct from new.end_ms then
        raise check_violation using message =
            'evidence timestamps must match the typed source locator';
    end if;
    return new;
end;
$$;

create trigger evidence_units_validate_locator
    before insert or update on video.evidence_units
    for each row execute function video.validate_evidence_locator();

create table video.evidence_embeddings (
    id bigint generated by default as identity primary key,
    owner_id uuid not null,
    video_id uuid not null,
    ingestion_version_id uuid not null,
    evidence_id text not null,
    embedding_kind text not null check (embedding_kind in ('text', 'image')),
    visual_region_id bigint,
    evidence_frame_id bigint,
    model_name text not null check (btrim(model_name) <> ''),
    model_revision text not null check (btrim(model_revision) <> ''),
    dimension integer not null check (dimension > 0),
    document_format_version text not null check (
        btrim(document_format_version) <> ''
    ),
    embedding_input_hash text not null check (
        embedding_input_hash ~ '^[0-9a-f]{64}$'
    ),
    embedding extensions.vector not null,
    created_at timestamptz not null default now(),
    foreign key (evidence_id, ingestion_version_id, video_id, owner_id)
        references video.evidence_units(
            id, ingestion_version_id, video_id, owner_id
        ) on delete cascade,
    foreign key (
        evidence_id, evidence_frame_id, ingestion_version_id,
        video_id, owner_id
    ) references video.evidence_units(
        id, frame_id, ingestion_version_id, video_id, owner_id
    ) on delete cascade,
    foreign key (
        visual_region_id, evidence_frame_id, ingestion_version_id,
        video_id, owner_id
    )
        references video.visual_regions(
            id, frame_id, ingestion_version_id, video_id, owner_id
        ) on delete cascade,
    check (extensions.vector_dims(embedding) = dimension),
    check (
        (embedding_kind = 'text'
            and visual_region_id is null
            and evidence_frame_id is null)
        or
        (embedding_kind = 'image'
            and visual_region_id is not null
            and evidence_frame_id is not null)
    )
);

create unique index idx_video_evidence_embeddings_text_unique
    on video.evidence_embeddings (
        owner_id, evidence_id, model_name, model_revision,
        document_format_version
    ) where embedding_kind = 'text';
create unique index idx_video_evidence_embeddings_image_unique
    on video.evidence_embeddings (
        owner_id, evidence_id, visual_region_id, model_name, model_revision,
        document_format_version
    ) where embedding_kind = 'image';
create index idx_video_evidence_embeddings_owner_version
    on video.evidence_embeddings (
        owner_id, video_id, ingestion_version_id, embedding_kind
    );

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'frames', 'visual_observations', 'visual_regions', 'visual_events',
        'evidence_units', 'evidence_embeddings'
    ] loop
        execute format('alter table video.%I enable row level security', table_name);
        execute format(
            'create policy %I on video.%I for select to authenticated '
            'using (owner_id = (select auth.uid()))',
            table_name || '_owner_read',
            table_name
        );
        execute format(
            'grant select on video.%I to authenticated',
            table_name
        );
    end loop;
end $$;

